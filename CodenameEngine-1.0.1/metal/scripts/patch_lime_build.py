#!/usr/bin/env python3
"""
Patch Lime's `project/Build.xml` for the bgfx/Metal backend.

Three things must be right -- all three were wrong in the first attempt:

1. `<compilerflag>` only applies to `<file>` declarations that come AFTER it in
   document order, and everything must live INSIDE `<files id="lime">`.
   A flag at the top level (outside the fileset, or after the files) silently does
   nothing -- which is why `-DLIME_METAL` never reached SDLWindow.cpp and the stale
   GL code kept getting linked.

2. The OpenGL bindings section must be excluded, otherwise every `lime_gl_*` primitive
   exists twice (OpenGLBindings.cpp and MetalBindings.cpp).

3. `libpath` / `lib` / `framework` belong in the linker `<target id="lime">`, not in the
   compile fileset.

Usage:
    patch_lime_build.py --lime <dir> --bgfx <dir> --bgfx-lib <dir> [--revert] [--force]
"""

import argparse
import os
import re
import sys

MARKER = "<!-- ==== CNE Metal backend (generated by metal/scripts/patch_lime_build.py) ==== -->"
MARKER2 = "<!-- ==== /CNE Metal backend ==== -->"
FILESET = '<files id="lime">'
TARGET_ANCHOR = '<files id="lime" />'
LEGACY = "<!-- ==== Codename Engine Metal backend (do not edit by hand) ==== -->"


def die(msg):
    print("patch_lime_build: error: " + msg, file=sys.stderr)
    sys.exit(1)


def strip_previous(src):
    """Remove anything a previous run (or an older version of this script) added."""
    src = re.sub(re.escape(MARKER) + r".*?" + re.escape(MARKER2) + r"[ \t]*\n?", "", src, flags=re.S)

    while LEGACY in src:
        first = src.index(LEGACY)
        second = src.find(LEGACY, first + len(LEGACY))
        if second < 0:
            src = src[:first] + src[first + len(LEGACY):]
            break
        end = second + len(LEGACY)
        while end < len(src) and src[end] in " \t\r\n":
            end += 1
        src = src[:first].rstrip(" \t\r\n") + "\n" + src[end:]

    src = re.sub(r"\n\t<!-- CNE_METAL_DEFINE.*?\n\t<compilerflag value=\"-DLIME_METAL\" if=\"LIME_METAL\" />",
                 "", src, flags=re.S)
    src = src.replace('\n\t<compilerflag value="-DLIME_METAL" if="LIME_METAL" />', "")
    src = src.replace('<set name="LIME_METAL" value="1" if="metal" />', '<set name="LIME_METAL" value="1" />')
    return src


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lime", required=True)
    ap.add_argument("--bgfx", required=True)
    ap.add_argument("--bgfx-lib", required=True)
    ap.add_argument("--revert", action="store_true")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    path = args.lime.rstrip("/") + "/project/Build.xml"
    if not os.path.isfile(path):
        die("cannot read %s" % path)
    src = open(path, encoding="utf-8").read()

    if args.revert:
        open(path, "w", encoding="utf-8").write(strip_previous(src))
        print("reverted: %s" % path)
        return 0

    if MARKER in src and not args.force:
        print("already patched: %s" % path)
        return 0

    src = strip_previous(src)

    for anchor in (FILESET, TARGET_ANCHOR, '<set name="LIME_OPENGL" value="1" />'):
        if anchor not in src:
            die("cannot find %r in %s" % (anchor, path))

    bgfx = args.bgfx.rstrip("/")
    bgfx_lib = args.bgfx_lib.rstrip("/")

    src = src.replace('<section if="LIME_OPENGL">',
                      '<section if="LIME_OPENGL" unless="LIME_METAL">', 1)

    compile_block = """
\t\t%s
\t\t<section if="LIME_METAL">

\t\t\t<compilerflag value="-DLIME_METAL" />
\t\t\t<compilerflag value="-I%s/include" />
\t\t\t<compilerflag value="-I%s/bx/include" />

\t\t\t<file name="src/graphics/metal/MetalContext.cpp" />
\t\t\t<file name="src/graphics/metal/MetalBindings.cpp" />

\t\t</section>
\t\t%s
""" % (MARKER, bgfx, bgfx, MARKER2)

    idx = src.index(FILESET) + len(FILESET)
    src = src[:idx] + compile_block + src[idx:]

    link_block = """
\t\t<section if="LIME_METAL">
\t\t\t<libpath name="%s" />
\t\t\t<lib name="-lbgfxRelease" />
\t\t\t<lib name="-lbxRelease" />
\t\t\t<lib name="-lbimgRelease" />
\t\t\t<lib name="-lbimg_decodeRelease" />
\t\t\t<framework name="Metal" />
\t\t\t<framework name="QuartzCore" />
\t\t\t<framework name="Foundation" />
\t\t\t<framework name="Cocoa" />
\t\t</section>
""" % bgfx_lib

    idx2 = src.index(TARGET_ANCHOR) + len(TARGET_ANCHOR)
    src = src[:idx2] + link_block + src[idx2:]

    if '<set name="LIME_METAL"' not in src:
        src = src.replace('<set name="LIME_OPENGL" value="1" />',
                          '<set name="LIME_OPENGL" value="1" />\n\t<set name="LIME_METAL" value="1" />', 1)

    open(path, "w", encoding="utf-8").write(src)
    print("patched: %s" % path)
    print("  compile flags + Metal sources : inside %s, before the file list" % FILESET)
    print("  bgfx link flags               : inside <target id=\"lime\">")
    print("  OpenGL bindings               : excluded when LIME_METAL")
    return 0


if __name__ == "__main__":
    sys.exit(main())
