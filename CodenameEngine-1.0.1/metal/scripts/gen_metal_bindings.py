#!/usr/bin/env python3
"""
Generate the Metal/bgfx replacement for Lime's `lime_gl_*` CFFI primitives.

Lime implements every OpenGL entry point in a single translation unit:
    <lime>/project/src/graphics/opengl/OpenGLBindings.cpp
which contains N `lime_gl_*` definitions plus a matching block of
`DEFINE_PRIME<n>[v] (lime_gl_*)` registrations.

For the Metal backend we must provide *all* of those symbols, otherwise
`OpenGLBindings.cpp`'s registrations fail to link.  This script:

  1. parses OpenGLBindings.cpp and extracts every signature exactly
     (return type + parameter list) and its arity;
  2. writes `native/MetalBindingsApi.h` - the declarations;
  3. writes `native/MetalBindingsStubs.inc` - weak stubs for every primitive that
     `native/MetalBindings.cpp` does not implement by hand, so that the backend
     always links and unimplemented calls fail loudly at runtime instead of
     crashing the process.

Usage:
    python3 metal/scripts/gen_metal_bindings.py [--lime <path-to-lime>]
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
METAL_DIR = os.path.dirname(HERE)
NATIVE_DIR = os.path.join(METAL_DIR, "native")

DEFAULT_LIME_CANDIDATES = [
    os.path.join(METAL_DIR, "..", "dev-libs", "lime"),
    os.path.join(METAL_DIR, "..", ".haxelib", "lime", "8,1,2"),
    os.path.expanduser("~/haxelib-dev/lime-812"),
    os.path.expanduser("~/haxelib-dev/lime"),
]

SIG_RE = re.compile(
    r"^\t([A-Za-z_][A-Za-z0-9_ :\*&<>]*?)\s+(lime_gl_[A-Za-z0-9_]+)\s*\((.*)\)\s*\{\s*$"
)
PRIME_RE = re.compile(r"DEFINE_PRIME(\d+)(v)?\s*\(\s*(lime_gl_[A-Za-z0-9_]+)\s*\)")

# Primitives implemented by hand in native/MetalBindings.cpp.
HAND_IMPLEMENTED = set()


def find_lime(explicit):
    if explicit:
        return explicit
    env = os.environ.get("LIME_DIR")
    if env:
        return env
    for c in DEFAULT_LIME_CANDIDATES:
        p = os.path.abspath(c)
        if os.path.isfile(os.path.join(p, "project", "src", "graphics", "opengl", "OpenGLBindings.cpp")):
            return p
    return None


def parse_bindings(path):
    src = open(path, "r", encoding="utf-8", errors="replace").read()
    sigs = {}
    for line in src.split("\n"):
        m = SIG_RE.match(line)
        if m:
            sigs[m.group(2)] = (m.group(1).strip(), m.group(3).strip())
    arity = {}
    for m in PRIME_RE.finditer(src):
        arity[m.group(3)] = (int(m.group(1)), m.group(2) == "v")
    return sigs, arity


def split_params(args):
    if args.strip() == "":
        return []
    out, depth, cur = [], 0, ""
    for ch in args:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def gen_api_header(sigs, arity, out_path):
    lines = [
        "// AUTO-GENERATED by metal/scripts/gen_metal_bindings.py - do not edit by hand.",
        "// Complete `lime_gl_*` surface extracted from Lime's OpenGLBindings.cpp.",
        "#ifndef LIME_GRAPHICS_METAL_METAL_BINDINGS_API_H",
        "#define LIME_GRAPHICS_METAL_METAL_BINDINGS_API_H",
        "",
        "#include <system/CFFI.h>",
        "#include <system/CFFIPointer.h>",
        "#include <utils/Bytes.h>",
        "",
        "namespace lime {",
        "",
    ]
    for name in sorted(sigs):
        ret, args = sigs[name]
        lines.append("\t%s %s (%s);" % (ret, name, args))
    lines += ["", "}", "", "#endif", ""]
    open(out_path, "w").write("\n".join(lines))
    return len(sigs)


def gen_stubs(sigs, arity, out_path):
    """Emit `#define`-free stub bodies for primitives not hand-implemented."""
    lines = [
        "// AUTO-GENERATED by metal/scripts/gen_metal_bindings.py - do not edit by hand.",
        "//",
        "// Stubs for the primitives this backend does not implement yet.  They are",
        "// compiled into the Metal build so the primitive registration block always",
        "// links; every call is reported once through the MetalBackend log and is then",
        "// a no-op.  `metal/README.md` tracks which ones are still missing.",
        "",
    ]
    todo = []
    for name in sorted(sigs):
        if name in HAND_IMPLEMENTED:
            continue
        ret, args = sigs[name]
        params = split_params(args)
        todo.append(name)
        body = [
            "\t%s %s (%s) {" % (ret, name, args),
            "\t\tMetalContext::ReportUnimplemented (\"%s\");" % name,
        ]
        if ret == "int":
            body.append("\t\treturn 0;")
        elif ret == "bool":
            body.append("\t\treturn false;")
        elif ret == "float":
            body.append("\t\treturn 0.0f;")
        elif ret == "double":
            body.append("\t\treturn 0.0;")
        elif ret == "value":
            body.append("\t\treturn alloc_null ();")
        body.append("\t}")
        body.append("")
        lines += body
    open(out_path, "w").write("\n".join(lines))
    return todo


def gen_registration(arity, out_path):
    """Emit the DEFINE_PRIME block that publishes every primitive to Haxe."""
    order = ["DEFINE_PRIME0", "DEFINE_PRIME0v",
             "DEFINE_PRIME1", "DEFINE_PRIME1v", "DEFINE_PRIME2", "DEFINE_PRIME2v",
             "DEFINE_PRIME3", "DEFINE_PRIME3v", "DEFINE_PRIME4", "DEFINE_PRIME4v",
             "DEFINE_PRIME5v", "DEFINE_PRIME6v", "DEFINE_PRIME7v", "DEFINE_PRIME8v",
             "DEFINE_PRIME9v", "DEFINE_PRIME10v", "DEFINE_PRIME11v"]
    buckets = {k: [] for k in order}
    for name, (n, is_v) in sorted(arity.items()):
        key = "DEFINE_PRIME%d%s" % (n, "v" if is_v else "")
        buckets.setdefault(key, []).append(name)

    lines = [
        "// AUTO-GENERATED by metal/scripts/gen_metal_bindings.py - do not edit by hand.",
        "//",
        "// Primitive registration block, equivalent to the one at the bottom of Lime's",
        "// OpenGLBindings.cpp.  Every `lime_gl_*` primitive plus the Metal-only helpers",
        "// are published here.",
        "",
    ]
    for key in order:
        names = buckets.get(key)
        if not names:
            continue
        lines.append("\t// %s" % key)
        for n in names:
            lines.append("\t%s (%s);" % (key, n))
        lines.append("")

    lines.append("\t// Metal-only helpers")
    lines.append("\tDEFINE_PRIME3v (lime_metal_configure_program);")
    lines.append("\tDEFINE_PRIME0 (lime_metal_is_metal);")
    lines.append("")

    open(out_path, "w").write("\n".join(lines))
    return sum(len(v) for v in buckets.values())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lime")
    ap.add_argument("--implemented", nargs="*", default=None,
                    help="extra primitive names considered hand-implemented")
    args = ap.parse_args()

    lime = find_lime(args.lime)
    if not lime:
        print("error: could not locate a Lime checkout with project/src/graphics/opengl/OpenGLBindings.cpp",
              file=sys.stderr)
        print("       pass --lime <path> or set LIME_DIR", file=sys.stderr)
        return 2

    src_path = os.path.join(lime, "project", "src", "graphics", "opengl", "OpenGLBindings.cpp")
    sigs, arity = parse_bindings(src_path)
    if not sigs:
        print("error: no lime_gl_* definitions parsed from " + src_path, file=sys.stderr)
        return 2

    # Only functions that are actually registered with DEFINE_PRIME are CFFI
    # primitives.  Lime also has a few plain `static` helpers in the same file
    # (e.g. lime_gl_swap_rb) that must not get a stub.
    non_primitives = [n for n in sigs if n not in arity]
    if non_primitives:
        print("note: %d lime_gl_* definitions are internal helpers, skipped: %s"
              % (len(non_primitives), ", ".join(sorted(non_primitives)[:5])))
    sigs = {n: v for n, v in sigs.items() if n in arity}

    # names implemented by hand live in MetalBindings.cpp as `//@impl <name>` markers
    # `//@impl` markers are collected from MetalBindings.cpp and from every
    # hand-written fragment it includes (MetalUniforms.inc, MetalObjects.inc).
    implemented = set(args.implemented or [])
    generated = {"MetalBindingsStubs.inc", "MetalBindingsRegister.inc"}
    impl_files = sorted(
        f for f in os.listdir(NATIVE_DIR)
        if (f.endswith(".cpp") or f.endswith(".inc")) and f not in generated
    )
    for name in impl_files:
        impl_path = os.path.join(NATIVE_DIR, name)
        if os.path.isfile(impl_path):
            text = open(impl_path, encoding="utf-8", errors="replace").read()
            implemented |= set(re.findall(r"//@impl\s+(lime_gl_[A-Za-z0-9_]+)", text))
    HAND_IMPLEMENTED.update(implemented)

    os.makedirs(NATIVE_DIR, exist_ok=True)
    n_api = gen_api_header(sigs, arity, os.path.join(NATIVE_DIR, "MetalBindingsApi.h"))
    todo = gen_stubs(sigs, arity, os.path.join(NATIVE_DIR, "MetalBindingsStubs.inc"))
    n_reg = gen_registration(arity, os.path.join(NATIVE_DIR, "MetalBindingsRegister.inc"))

    report = os.path.join(NATIVE_DIR, "MetalBindingsStatus.txt")
    with open(report, "w") as f:
        f.write("lime source: %s\n" % src_path)
        f.write("total primitives : %d\n" % len(sigs))
        f.write("implemented      : %d\n" % len(implemented))
        f.write("stubbed          : %d\n" % len(todo))
        f.write("\n-- implemented --\n")
        for n in sorted(implemented):
            f.write(n + "\n")
        f.write("\n-- stubbed (TODO) --\n")
        for n in todo:
            f.write(n + "\n")

    print("lime            : %s" % lime)
    print("primitives      : %d" % n_api)
    print("implemented     : %d" % len(implemented))
    print("stubbed         : %d" % len(todo))
    print("registered      : %d primitives" % n_reg)
    print("scanned         : %s" % ", ".join(impl_files))
    print("wrote           : MetalBindingsApi.h, MetalBindingsStubs.inc, MetalBindingsRegister.inc, MetalBindingsStatus.txt")
    return 0


if __name__ == "__main__":
    sys.exit(main())
